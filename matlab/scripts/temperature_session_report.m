function N = temperature_session_report(day, fromTime, toTime, varargin)
%TEMPERATURE_SESSION_REPORT  One rig session's runs, measured and against the model fitted to it.
%
%   N = temperature_session_report('2026-10-26', '01:50')            % from 01:50 to midnight
%   N = temperature_session_report('2026-10-26', '01:50', '07:00')
%   ... 'PlantRun', 'TEMP-R0004_...', 'Ta', 24   identify the plant on this run (any session,
%                                     any result) with this room temperature, instead of T1
%   ... 'Note', 'text'               an observation the data cannot state, printed under the title
%
%   Reads the session's TEMP runs from data/ (latest FINISHED run of each preset), then:
%     T1  heating and cooling: K, tau, theta (templab.ident.fitThermal on the whole record),
%         the initial heating and cooling rates; this fit becomes the model for the rest
%     T2  on-off at each setpoint: swing (peak to peak) and switching period once settled
%     T3  hysteresis: swing and switches per minute against the band
%     T4  moving average: window span, sensor values inside it, filter delay, overshoot, switches
%     T5  P control: steady error against r - e = (r - Ta) / (1 + K Kp / 255), and the light changes
%     T6  PI: steady error and overshoot
%   Every run is also simulated with its own settings on the fitted model (the room at the
%   session's start, the run's own starting temperature), drawn grey under the rig's trace.
%   Writes results/reports/temperature/<day>/<HHMM of fromTime>/REPORT.md and *.png. Every
%   number comes from data/.
    if nargin < 2, fromTime = '00:00'; end
    if nargin < 3, toTime = '24:00'; end
    o = struct('PlantRun', '', 'Ta', NaN, 'Note', '');
    for k = 1:2:numel(varargin), o.(varargin{k}) = varargin{k + 1}; end
    root = templab.repoRoot();
    out = fullfile(root, 'results', 'reports', 'temperature', day, strrep(fromTime, ':', ''));
    if ~isfolder(out), mkdir(out); end
    Rg = templab.data.register(); Rg = Rg(strcmp(Rg.apparatus, 'TEMP'), :);
    created = datetime(extractBefore(Rg.created, 20), 'InputFormat', 'yyyy-MM-dd''T''HH:mm:ss');
    t0 = datetime([day ' ' fromTime], 'InputFormat', 'yyyy-MM-dd HH:mm');
    t1 = dateshift(t0, 'start', 'day') + duration(toTime, 'InputFormat', 'hh:mm');
    Rall = Rg; Rg = Rg(created >= t0 & created < t1, :);
    L = {}; N = struct('day', day, 'runs', height(Rg));
    say('# Temperature control: rig session %s', day);
    say('');
    say(['Generated by `matlab/scripts/temperature_session_report.m` from `data/` (%d runs from %s to %s). ' ...
         'Philips 40 W bulb through a Fotek SSR-40DA, DHT11 read every 2 s, Arduino Uno. Grey in every figure ' ...
         'is the identified model (section T1), running each run''s own settings.'], height(Rg), fromTime, toTime);
    say('');

    if ~isempty(o.Note), say('**Observation.** %s', o.Note); say(''); end

    % ------------------------------------------------------------------ T1: the plant
    say('## T1 Heating and cooling: the plant');
    r = pick('T1', 'heater step'); Ta = NaN;
    if ~isempty(o.PlantRun), r = table2struct(Rall(strcmp(Rall.run_id, o.PlantRun), :)); end
    if isempty(r)
        say('No finished T1 run in this session: the model keeps its ASSUMED values.'); say('');
        c0 = templab.temperature.defaultConfig();
    else
        [T, ~] = loadRun(r.run_id);
        h = double(T.heater); y = T.temp_raw; t = T.t_s;
        ok = isfinite(y); Ta = y(find(ok, 1)); if isfinite(o.Ta), Ta = o.Ta; end
        m = templab.ident.fitThermal(t(ok), y(ok), h(ok), Ta);
        c0 = templab.temperature.withFOPDT(templab.temperature.defaultConfig(), m.K, m.tau, m.theta);
        c0.P.T_amb = Ta;
        kOn = find(h > 0, 1, 'last'); yHot = max(y(1:kOn));
        heatRate = slope(t, y, t(find(ok, 1)) + [10 40]); coolRate = slope(t, y, t(kOn) + [10 40]);
        res = min(diff(unique(y(ok))));
        say(['Plant identified on `%s`. Room **%.1f °C**. Bulb fully on for the first %.0f s (up to %.1f °C), then off ' ...
             'for the rest of the run. Fit of tau dT/dt = K u(t - theta) - (T - Ta) to the whole record (heating and cooling ' ...
             'together, so no final value has to be guessed): **K = %.1f °C at full power, tau = %.0f s, theta = %.0f s** ' ...
             '(RMSE %.2f °C). At full power the reading would settle near %.0f °C. ' ...
             'Heating starts at %.2f °C/s, cooling at %.2f °C/s. %s'], ...
            r.run_id, Ta, t(kOn), yHot, m.K, m.tau, m.theta, m.rmse, Ta + m.K, heatRate, coolRate, coolText(heatRate, coolRate, yHot - Ta, m.K));
        say('');
        say(['The sensor: a new value every %.1f s (the firmware reads every 2 s; the datasheet asks for > 2 s), ' ...
             'smallest step seen %.1f °C (this DHT11 reports tenths; its datasheet states 1 °C).'], ...
            median(diff(t(find(diff(y) ~= 0) + 1))), res);
        S = sim(r, c0);
        plotRun(T, S, sprintf('T1 heating and cooling (%s)', r.run_id), 'T1_heating_cooling.png');
        say(''); say('![T1](T1_heating_cooling.png)'); say('');
        N.K = m.K; N.tau = m.tau; N.theta = m.theta; N.Ta = Ta;
    end
    Kfit = c0.P.eta_heat * c0.P.P_bulb * c0.P.R_th;

    % ------------------------------------------------------------------ T2: on-off
    R = runsOf('T2');
    if ~isempty(R)
        say('## T2 On-off');
        say('| setpoint (°C) | swing, rig (°C) | period, rig (s) | switches / min | swing, model | period, model | run |');
        say('|---:|---:|---:|---:|---:|---:|---|');
        figs = {};
        for r = R
            [T, v] = loadRun(r.run_id); S = sim(r, c0);
            a = cycles(T.t_s, T.temp_raw, double(T.heater)); b = cycles(S.t, S.Traw, double(S.heat > 0));
            say('| %g | %.1f | %s | %.1f | %.1f | %s | `%s` |', v.setpoint, a.swing, n0(a.period), a.perMin, b.swing, n0(b.period), r.run_id);
            figs{end + 1} = {T, S, sprintf('on-off %g °C (%s)', v.setpoint, r.run_id)}; %#ok<AGROW>
        end
        multiPlot(figs, 'T2_on_off.png');
        say('');
        say(['Swing and period are measured once the reading has first reached the setpoint. The bulb switches when ' ...
             'the reading crosses the setpoint, but the temperature keeps moving for the dead time theta and the sensor''s ' ...
             'lag before the reading turns: that sets the swing. Above 50 °C the DHT11 is outside its datasheet.']);
        say(''); say('![T2](T2_on_off.png)'); say('');
    end

    % ------------------------------------------------------------------ T3: hysteresis
    R = runsOf('T3');
    if ~isempty(R)
        say('## T3 Hysteresis');
        say('| setpoint (°C) | band (°C) | swing, rig (°C) | switches / min, rig | swing, model | switches / min, model | run |');
        say('|---:|---:|---:|---:|---:|---:|---|');
        figs = {};
        for r = R
            [T, v] = loadRun(r.run_id); S = sim(r, c0);
            a = cycles(T.t_s, T.temp_raw, double(T.heater)); b = cycles(S.t, S.Traw, double(S.heat > 0));
            say('| %g | %g | %.1f | %.1f | %.1f | %.1f | `%s` |', v.setpoint, v.hyst, a.swing, a.perMin, b.swing, b.perMin, r.run_id);
            figs{end + 1} = {T, S, sprintf('hysteresis band %g °C at %g °C (%s)', v.hyst, v.setpoint, r.run_id)}; %#ok<AGROW>
        end
        multiPlot(figs, 'T3_hysteresis.png');
        say(['The bulb switches on below setpoint - band/2 and off above setpoint + band/2: a wider band, fewer ' ...
             'switches and a wider swing. With 0.1 °C sensor steps every 2 s, a band under about 0.2 °C acts as on-off.']);
        say(''); say('![T3](T3_hysteresis.png)'); say('');
    end

    % ------------------------------------------------------------------ T4: moving average
    R = runsOf('T4');
    if ~isempty(R)
        say('## T4 Moving average (Ts = 10 ms)');
        say('| N | window (s) | sensor values in it | delay (N-1)Ts/2 (s) | overshoot, rig (°C) | switches / min, rig | run |');
        say('|---:|---:|---:|---:|---:|---:|---|');
        figs = {};
        for r = R
            [T, v] = loadRun(r.run_id); S = sim(r, c0); Nw = v.window;
            a = cycles(T.t_s, T.temp_raw, double(T.heater));
            span = Nw * 0.01;
            say('| %d | %.2f | %d | %.3f | %.1f | %.1f | `%s` |', Nw, span, floor(span / 2) + 1, (Nw - 1) * 0.01 / 2, a.overshoot, a.perMin, r.run_id);
            figs{end + 1} = {T, S, sprintf('moving average N = %d at %g °C (%s)', Nw, v.setpoint, r.run_id)}; %#ok<AGROW>
        end
        multiPlot(figs, 'T4_moving_average.png');
        say('');
        say(['With a new sensor value only every 2 s, a window of 10 samples (0.1 s) almost always holds one value: it ' ...
             'filters nothing. 500 samples (5 s) hold two or three values: the switching point moves between them, and ' ...
             'the filter adds about 2.5 s of delay, which widens the swing.']);
        say(''); say('![T4](T4_moving_average.png)'); say('');
    end

    % ------------------------------------------------------------------ T5: P control
    R = runsOf('T5');
    if ~isempty(R)
        say('## T5 P control');
        say(['Steady error predicted for a first-order plant with gain K: e = (r - Ta) / (1 + K Kp / 255), with K = %.1f °C ' ...
             'at full power and Ta = %.1f °C. It needs the run to be several tau long; a shorter run is still on its way.'], Kfit, c0.P.T_amb);
        say('');
        say('| mode | setpoint (°C) | Kp | steady error, rig (°C) | predicted (°C) | light changes / min | run |');
        say('|---|---:|---:|---:|---:|---:|---|');
        figs = {};
        for r = R
            [T, v] = loadRun(r.run_id); S = sim(r, c0);
            tail = T.t_s >= 0.6 * T.t_s(end);
            e = mean(v.setpoint - T.temp_raw(tail), 'omitnan');
            ep = (v.setpoint - c0.P.T_amb) / (1 + Kfit * v.Kp / 255);
            sw = nnz(diff(double(T.heater)) ~= 0) / (T.t_s(end) / 60);
            say('| %s | %g | %g | %.2f | %.2f | %.0f | `%s` |', v.mode, v.setpoint, v.Kp, e, ep, sw, r.run_id);
            figs{end + 1} = {T, S, sprintf('%s Kp %g at %g °C (%s)', v.mode, v.Kp, v.setpoint, r.run_id)}; %#ok<AGROW>
        end
        multiPlot(figs, 'T5_P_control.png');
        say('');
        say(['The SSR switches only at the mains zero crossings, every 10 ms. Driven by the 490 Hz PWM of pin 9, it ' ...
             'samples the PWM at each crossing: for u = 128 the bulb gets a pseudo-random half of the half-cycles, ' ...
             'not a steady half power. That is the flicker near e = 0. Time-proportioning (on for u/255 of a 2 s ' ...
             'window) gives the same mean power with far fewer light changes.']);
        say(''); say('![T5](T5_P_control.png)'); say('');
    end

    % ------------------------------------------------------------------ T6: PI
    R = runsOf('T6');
    for r = R
        [T, v] = loadRun(r.run_id); S = sim(r, c0);
        tail = T.t_s >= 0.6 * T.t_s(end);
        reach = find(T.temp_raw >= v.setpoint, 1);
        ov = NaN; if ~isempty(reach), ov = max(T.temp_raw(reach:end)) - v.setpoint; end
        say('## T6 PI');
        say(['PI (Kp %g, Ki %g, clamping anti-windup) at %g °C: mean error over the last 40 %% of the run **%.2f °C**, ' ...
             'overshoot %.1f °C (`%s`).'], v.Kp, v.Ki, v.setpoint, mean(v.setpoint - T.temp_raw(tail), 'omitnan'), ov, r.run_id);
        plotRun(T, S, sprintf('PI Kp %g Ki %g (%s)', v.Kp, v.Ki, r.run_id), 'T6_PI.png');
        say(''); say('![T6](T6_PI.png)'); say('');
    end

    % ------------------------------------------------------------------ faults
    say('## Runs stopped by the firmware');
    st = Rg(~startsWith(Rg.result, 'FINISHED'), :);
    if height(st) == 0, say('None.'); end
    for k = 1:height(st), say('- `%s` %s: %s', st.run_id{k}, st.experiment{k}, st.result{k}); end
    fid = fopen(fullfile(out, 'REPORT.md'), 'w'); fprintf(fid, '%s\n', L{:}); fclose(fid);
    fprintf('report -> %s\n', fullfile(out, 'REPORT.md'));

    % ================================================================== helpers
    function r = pick(tag, text)
        j = find(strcmp(Rg.mission, tag) & contains(Rg.experiment, text) & startsWith(Rg.result, 'FINISHED'), 1, 'last');
        if isempty(j), r = []; else, r = table2struct(Rg(j, :)); end
    end
    function R = runsOf(tag)
        j = find(strcmp(Rg.mission, tag) & startsWith(Rg.result, 'FINISHED'));
        R = table2struct(Rg(j, :))';
    end
    function [T, v, J] = loadRun(id)
        T = readtable(fullfile(root, 'data', 'raw', 'temperature', [id '.csv']));
        J = jsondecode(fileread(fullfile(root, 'data', 'metadata', 'temperature', [id '.json'])));
        v = J.config_sent.values;
    end
    function S = sim(r, c0)
        [T, v] = loadRun(r.run_id);
        c = c0;
        for f = {'mode', 'setpoint', 'hyst', 'window', 'Kp', 'Ki', 'tprop'}
            if isfield(v, f{1}), c.(f{1}) = v.(f{1}); end
        end
        c.Tend = T.t_s(end); c.T0 = T.temp_raw(find(isfinite(T.temp_raw), 1));
        if strcmp(c.mode, 'TPROP'), c.ssr = 'average'; end
        S = templab.temperature.simulate(c);
    end
    function say(fmt, varargin), L{end + 1} = regexprep(sprintf(fmt, varargin{:}), '(?<![A-Za-z])NaN(?![A-Za-z])', '-'); end
    function save_(f, name), exportgraphics(f, fullfile(out, name), 'Resolution', 110); close(f); end
    function plotRun(T, S, ttl, name)
        f = figure('Visible', 'off', 'Position', [0 0 1000 520], 'Color', 'w'); try, theme(f, 'light'); catch, end
        tl = tiledlayout(f, 2, 1, 'TileSpacing', 'compact');
        ax = nexttile(tl); hold(ax, 'on'); grid(ax, 'on');
        plot(ax, S.t, S.Traw, '-', 'Color', [0.6 0.6 0.6], 'LineWidth', 1.5);
        plot(ax, T.t_s, T.temp_raw, '-', 'Color', [0.85 0.33 0.10], 'LineWidth', 1.2);
        yline(ax, T.setpoint(end), '--k'); ylabel(ax, '°C (DHT11)'); legend(ax, {'model', 'rig', 'setpoint'}, 'Location', 'best');
        title(ax, ttl, 'Interpreter', 'none');
        ax = nexttile(tl); hold(ax, 'on'); grid(ax, 'on');
        stairs(ax, T.t_s, double(T.heater), '-', 'Color', [0.85 0.33 0.10], 'LineWidth', 1.2); ylim(ax, [-0.1 1.1]);
        ylabel(ax, 'bulb on'); xlabel(ax, 't (s)');
        save_(f, name);
    end
    function multiPlot(figs, name)
        if isempty(figs), return; end
        f = figure('Visible', 'off', 'Position', [0 0 1000 260 * numel(figs)], 'Color', 'w'); try, theme(f, 'light'); catch, end
        tl = tiledlayout(f, numel(figs), 1, 'TileSpacing', 'compact');
        for i = 1:numel(figs)
            [T, S, ttl] = figs{i}{:};
            ax = nexttile(tl); hold(ax, 'on'); grid(ax, 'on');
            plot(ax, S.t, S.Traw, '-', 'Color', [0.6 0.6 0.6], 'LineWidth', 1.5);
            plot(ax, T.t_s, T.temp_raw, '-', 'Color', [0.85 0.33 0.10], 'LineWidth', 1.2);
            yline(ax, T.setpoint(end), '--k'); ylabel(ax, '°C'); title(ax, ttl, 'Interpreter', 'none');
        end
        xlabel(ax, 't (s)'); save_(f, name);
    end
end

function a = cycles(t, y, h)
    % once the reading first reaches the setpoint: swing (peak to peak), mean switching period
    % (time between bulb switch-ons), switches per minute (on and off), overshoot above the setpoint
    a = struct('swing', NaN, 'period', NaN, 'perMin', NaN, 'overshoot', NaN);
    ok = isfinite(y); t = t(ok); y = y(ok); h = h(ok);
    if numel(t) < 10, return; end
    on = find(diff(h) > 0) + 1;
    k0 = find(diff(h) < 0, 1) + 1;                    % the first switch-off: the setpoint was reached
    if isempty(k0), return; end
    tt = t(k0:end); yy = y(k0:end); hh = h(k0:end);
    a.swing = max(yy) - min(yy);
    a.overshoot = max(yy) - y(k0);
    on = on(on >= k0);
    if numel(on) >= 2, a.period = mean(diff(t(on))); end
    a.perMin = nnz(diff(hh) ~= 0) / ((tt(end) - tt(1)) / 60);
end

function s = slope(t, y, win)
    k = t >= win(1) & t <= win(2) & isfinite(y);
    if nnz(k) < 3, s = NaN; return; end
    p = polyfit(t(k), y(k), 1); s = p(1);
end

function s = n0(v), if isfinite(v), s = sprintf('%.0f', v); else, s = '-'; end, end

function s = coolText(heat, cool, rise, K)
    % first-order plant: heating starts at K / tau, cooling from a rise d at d / tau
    if ~isfinite(heat) || ~isfinite(cool), s = ''; return; end
    if abs(cool) < heat
        s = sprintf(['Cooling is slower: heating is driven by the full rise K = %.0f °C, cooling only by the %.0f °C ' ...
            'above the room, and it slows further as the box approaches room temperature.'], K, rise);
    else
        s = sprintf('Cooling from %.0f °C above the room is as fast as heating or faster: the rise was close to K.', rise);
    end
end
